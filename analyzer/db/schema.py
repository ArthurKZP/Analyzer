def ddl(statement: str, dialect: str) -> str:
    out = statement
    for token, sql in TYPES[dialect].items():
        out = out.replace("{" + token + "}", sql)
    return out


def version(db) -> int:
    return db.value("SELECT MAX(version) FROM schema_version", default=0)


def migrate(db) -> int:
    """Applique les migrations qui manquent ; renvoie la version du schéma."""
    db.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY, description TEXT NOT NULL, "
               "applique_le TEXT NOT NULL)")
    from . import now
    current = version(db)
    for number, description, statements in MIGRATIONS:
        if number <= current:
            continue
        with db.transaction():
            if version(db) >= number:  # appliquée entre-temps par un autre processus
                continue
            for statement in statements:
                db.execute(ddl(statement, db.dialect))
            db.execute("INSERT INTO schema_version (version, description, applique_le) VALUES (?, ?, ?)",
                       (number, description, now()))
    return version(db)
