"""Le schéma de la base, par migrations numérotées : chaque migration s'applique une fois, dans une transaction, et
son numéro est noté dans schema_version. Pour faire évoluer le schéma, ajouter une migration à la fin (ne jamais
modifier une migration déjà livrée).

Les types s'écrivent avec des repères remplacés selon la base : {ID} (clé numérique automatique), {REF} (référence à
une clé), {BLOB} (octets), {REAL} (nombre à virgule), {BIG} (grand entier).
"""
from __future__ import annotations

TYPES = {
    "sqlite": {"ID": "INTEGER PRIMARY KEY", "REF": "INTEGER", "BLOB": "BLOB", "REAL": "REAL", "BIG": "INTEGER"},
    "postgres": {"ID": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "REF": "BIGINT", "BLOB": "BYTEA",
                 "REAL": "DOUBLE PRECISION", "BIG": "BIGINT"},
}

